"""Test case generation: generate inputs, execute them, measure coverage and mutation score."""
from __future__ import annotations

from collections import Counter, defaultdict

from mltest.core.evaluator import Evaluator, Stopwatch
from mltest.core.factory import DataLoaderFactory, ModuleFactory, TestStrategyFactory
from mltest.core.pipeline import PipelineContext
from mltest.modules.base import TestingModule
from mltest.programs.mutation import describe_call, killing_test, mutant_adapters
from mltest.reporting import write_csv, write_json

_PYTEST_TEMPLATE = '''"""Generated by mltest ({strategy} strategy): regression tests for {func}()."""
import pytest

from mltest.programs.subjects import {func}

CASES = [
{cases}
]


@pytest.mark.parametrize("args, expected", CASES)
def test_{func}_{strategy}(args, expected):
    assert {func}(*args) == expected
'''


@ModuleFactory.register("test_generation")
class TestGenerationModule(TestingModule):
    __test__ = False
    name = "test_generation"
    summary_columns = ("program", "strategy", "tests", "line_coverage", "branch_coverage", "boundary_coverage",
                       "mutants_killed", "mutation_score", "generation_time")

    def load(self, ctx: PipelineContext) -> PipelineContext:
        ctx["programs"] = DataLoaderFactory.create("programs", names=self.settings.get("programs")).load()
        self.say(f"loaded {len(ctx['programs'])} programs: {', '.join(p.name for p in ctx['programs'])}")
        return ctx

    def preprocess(self, ctx: PipelineContext) -> PipelineContext:
        """Static analysis (lines, decisions, constants) and mutant generation."""
        ctx["mutants"] = {}
        for program in ctx["programs"]:
            info = program.static
            ctx["mutants"][program.name] = mutant_adapters(program)
            self.say(f"{program.name}: {len(info.executable_lines)} lines, {len(info.decision_lines)} decisions, "
                     f"{len(ctx['mutants'][program.name])} mutants")
        return ctx

    def execute(self, ctx: PipelineContext) -> PipelineContext:
        budget = int(self.settings.get("budget", 200))
        strategy_params = self.settings.get("strategy_params", {})
        suites = []
        for program in ctx["programs"]:
            for name in self.settings.get("strategies", ["random", "search", "ml"]):
                strategy = TestStrategyFactory.create(name, seed=self.seed, **strategy_params.get(name, {}))
                with Stopwatch() as gen_time:
                    inputs = strategy.generate(program, budget)
                with Stopwatch() as exec_time:
                    results = [program.run(x) for x in inputs]
                suites.append({"program": program, "strategy": name, "results": results,
                               "generation_time": gen_time.seconds, "execution_time": exec_time.seconds})
                self.say(f"{program.name}/{name}: {len(results)} tests generated")
                for result in self._diverse_examples(results):
                    self.say(f"    e.g. {describe_call(program.spec.func.__name__, result)}")
        ctx["suites"] = suites
        return ctx

    def _diverse_examples(self, results: list) -> list:
        """Up to ``show_examples`` tests with different outputs, rarest outputs first.

        Rare outputs (an equilateral triangle, a leap-year February) are the hard
        cases, so they show best what each strategy managed to reach.
        """
        limit = int(self.settings.get("show_examples", 3))
        counts = Counter(r.signature() for r in results)
        first = {}
        for result in results:
            first.setdefault(result.signature(), result)
        return sorted(first.values(), key=lambda r: counts[r.signature()])[:limit]

    def evaluate(self, ctx: PipelineContext) -> PipelineContext:
        records = []
        for suite in ctx["suites"]:
            program, results = suite["program"], suite["results"]
            mutants = ctx["mutants"][program.name]
            with Stopwatch() as mutation_time:
                outcomes = [(m, killing_test(adapter, results)) for m, adapter in mutants]
            suite["killed"] = [(m, *evidence) for m, evidence in outcomes if evidence is not None]
            suite["survivors"] = survivors = [m for m, evidence in outcomes if evidence is None]
            killed = len(mutants) - len(survivors)
            records.append({
                "name": f"{program.name}/{suite['strategy']}",
                "program": program.name,
                "strategy": suite["strategy"],
                "tests": len(results),
                "line_coverage": program.line_coverage(results),
                "branch_coverage": program.branch_coverage(results),
                "boundary_coverage": program.boundary_coverage(results),
                "mutants": len(mutants),
                "mutants_killed": killed,
                "mutation_score": Evaluator.mutation_score(killed, len(mutants)),
                "generation_time": suite["generation_time"],
                "execution_time": suite["execution_time"],
                "mutation_analysis_time": mutation_time.seconds,
            })
        ctx["metrics"] = records
        ctx["strategy_summary"] = self._per_strategy(records)
        self.emit("metrics", records=records)
        self._show_bug_examples(ctx["suites"])
        for row in ctx["strategy_summary"]:
            self.say(f"{row['strategy']:<8} avg branch coverage {row['branch_coverage']:.1%}, "
                     f"avg mutation score {row['mutation_score']:.1%}, avg tests {row['tests']:.0f}")
        return ctx

    def _show_bug_examples(self, suites: list[dict]) -> None:
        """For each program, show planted bugs the last strategy's tests caught or missed."""
        limit = int(self.settings.get("show_examples", 3))
        last = {s["program"].name: s for s in suites}  # one suite per program keeps output short
        for name, suite in last.items():
            func = suite["program"].spec.func.__name__
            self.say(f"{name}: bugs caught by the {suite['strategy']} tests "
                     f"({len(suite['killed'])} caught, {len(suite['survivors'])} missed)")
            for mutant, original, observed in suite["killed"][:limit]:
                self.say(f"    CAUGHT  bug at {mutant.description}: test {describe_call(func, original)}, "
                         f"buggy version returned {describe_call(func, observed).split(' -> ')[1]}")
            for mutant in suite["survivors"][:1]:
                self.say(f"    MISSED  bug at {mutant.description} (no test exposed it)")

    @staticmethod
    def _per_strategy(records: list[dict]) -> list[dict]:
        grouped = defaultdict(list)
        for r in records:
            grouped[r["strategy"]].append(r)
        keys = ("tests", "line_coverage", "branch_coverage", "boundary_coverage", "mutation_score",
                "generation_time")
        return [{"name": s, "strategy": s, **{k: sum(r[k] for r in rs) / len(rs) for k in keys}}
                for s, rs in grouped.items()]

    def report(self, ctx: PipelineContext) -> PipelineContext:
        out = self.output_dir
        cases = [
            {"program": s["program"].name, "strategy": s["strategy"], "inputs": list(r.inputs),
             "expected_output": r.output, "error": r.error}
            for s in ctx["suites"] for r in s["results"]
        ]
        artifacts = [
            write_json(out / "test_cases.json", cases),
            write_csv(out / "test_cases.csv", [{**c, "inputs": repr(tuple(c["inputs"]))} for c in cases]),
            write_csv(out / "metrics.csv", ctx["metrics"]),
            write_csv(out / "strategy_summary.csv", ctx["strategy_summary"]),
            write_csv(out / "surviving_mutants.csv", [
                {"program": s["program"].name, "strategy": s["strategy"], "mutant": m.id, "change": m.description}
                for s in ctx["suites"] for m in s["survivors"]
            ]),
            write_csv(out / "caught_bugs.csv", [
                {"program": s["program"].name, "strategy": s["strategy"], "mutant": m.id, "change": m.description,
                 "caught_by_inputs": repr(original.inputs), "correct_output": repr(original.output),
                 "buggy_output": repr(observed.output) if observed.ok else observed.error}
                for s in ctx["suites"] for m, original, observed in s["killed"]
            ]),
        ]
        if self.settings.get("write_pytest_files", True):
            artifacts += self._write_pytest_files(ctx["suites"])
        ctx["artifacts"] = [str(a) for a in artifacts]
        self.say(f"wrote {len(cases)} test cases and {len(artifacts)} files to {out}")
        return ctx

    def _write_pytest_files(self, suites: list[dict]) -> list:
        folder = self.output_dir / "generated_tests"
        folder.mkdir(exist_ok=True)
        written = []
        for suite in suites:
            func = suite["program"].spec.func.__name__
            cases = "\n".join(f"    ({r.inputs!r}, {r.output!r})," for r in suite["results"] if r.ok)
            path = folder / f"test_{func}_{suite['strategy']}.py"
            path.write_text(_PYTEST_TEMPLATE.format(strategy=suite["strategy"], func=func, cases=cases),
                            encoding="utf-8")
            written.append(path)
        return written
